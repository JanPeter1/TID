static bool german_get_glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *dsc,
                                   uint32_t letter, uint32_t letter_next)
{
    (void)letter_next;
    const german_font_data_t *font_data = font->dsc;
    for (uint32_t i = 0; i < font_data->count; i++) {
        const german_glyph_t *glyph = &font_data->glyphs[i];
        if (glyph->codepoint != letter) continue;
        memset(dsc, 0, sizeof(*dsc));
        dsc->resolved_font = font;
        dsc->gid.index = i;
        dsc->format = LV_FONT_GLYPH_FORMAT_A8;
        dsc->adv_w = glyph->adv_w;
        dsc->box_w = glyph->box_w;
        dsc->box_h = glyph->box_h;
        dsc->ofs_x = glyph->ofs_x;
        dsc->ofs_y = glyph->ofs_y;
        dsc->stride = glyph->stride;
        return true;
    }
    return false;
}

static const void *german_get_glyph_bitmap(lv_font_glyph_dsc_t *dsc, lv_draw_buf_t *draw_buf)
{
    (void)draw_buf;
    const lv_font_t *font = dsc->resolved_font;
    const german_font_data_t *font_data = font->dsc;
    if (dsc->gid.index >= font_data->count) return NULL;
    return font_data->glyphs[dsc->gid.index].bitmap;
}

static void german_release_glyph(const lv_font_t *font, lv_font_glyph_dsc_t *dsc)
{
    (void)font;
    (void)dsc;
}

